<#
.SYNOPSIS
    Writes src\Plicbox.App\THIRD-PARTY-NOTICES.txt: every package the app ships, with its copyright and licence, as
    their licences ask of anyone passing them on. Read from the app's restored packages (obj\project.assets.json),
    so it follows every dependency change; release.ps1 runs it, and a test fails when the file is out of date.
.EXAMPLE
    .\licenses\update-notices.ps1
#>
$ErrorActionPreference = 'Stop'
$root = Split-Path $PSScriptRoot
$assetsPath = Join-Path $root 'src\Plicbox.App\obj\project.assets.json'
$out = Join-Path $root 'src\Plicbox.App\THIRD-PARTY-NOTICES.txt'
if (-not (Test-Path $assetsPath)) { dotnet restore (Join-Path $root 'src\Plicbox.App') | Out-Null }

$assets = Get-Content $assetsPath -Raw | ConvertFrom-Json -AsHashtable
$packagesRoot = @($assets.packageFolders.Keys)[0]
$target = @($assets.targets.Keys | Where-Object { $_ -notmatch '/' })[0]
$templates = @{
    'MIT'          = Get-Content (Join-Path $PSScriptRoot 'MIT.txt') -Raw
    'BSD-3-Clause' = Get-Content (Join-Path $PSScriptRoot 'BSD-3-Clause.txt') -Raw
}
$rule = '=' * 80
$thin = '-' * 80

# One entry per package; packages with the same licence, copyright and text are listed together.
$groups = [ordered]@{}
foreach ($key in ($assets.targets[$target].Keys | Sort-Object)) {
    if ($assets.targets[$target][$key].type -ne 'package') { continue }
    $library = $assets.libraries[$key]
    $dir = Join-Path $packagesRoot $library.path
    $nuspec = [xml](Get-Content (Join-Path $dir ($library.files | Where-Object { $_ -like '*.nuspec' } | Select-Object -First 1)) -Raw)
    $meta = $nuspec.package.metadata
    $copyright = "$($meta.copyright)".Trim()
    if (-not $copyright) { $copyright = "Copyright (c) $($meta.authors)" }
    elseif ($copyright -notmatch '^(Copyright|\(c\)|©)') { $copyright = "Copyright (c) $copyright" }

    $license = $meta.license
    $kind = if ($license -and $license.type -eq 'expression') { $license.'#text' } elseif ($license) { 'see below' } else { "see $($meta.licenseUrl)" }
    $text = switch ($kind) {
        { $templates.ContainsKey($_) } { $templates[$_] -replace '(?m)^Copyright \(c\) \[year\],? \[fullname\][ \t]*$', $copyright; break }
        'Apache-2.0' { "$copyright`n`nLicensed under the Apache License, Version 2.0 (full text at the end of this file)."; break }
        'see below' { Get-Content (Join-Path $dir $license.'#text') -Raw; break }
        default { $copyright }
    }
    # Apache-2.0 asks for a package's NOTICE file to travel with it.
    $notice = Get-ChildItem $dir -File -Filter 'NOTICE*' -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($notice) { $text = "$($text.TrimEnd())`n`n$((Get-Content $notice.FullName -Raw).TrimEnd())" }

    $id = "$kind|$($text.Trim())"
    if (-not $groups.Contains($id)) { $groups[$id] = @{ Kind = $kind; Text = $text.Trim(); Packages = [System.Collections.Generic.List[string]]::new() } }
    $groups[$id].Packages.Add("$($meta.id) $($meta.version)$(if ($meta.projectUrl) { "  ($($meta.projectUrl))" })")
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('Plicbox: third-party notices')
[void]$sb.AppendLine()
[void]$sb.AppendLine('Plicbox is free software under the GNU General Public License, version 3 (see LICENSE and NOTICE.md).')
[void]$sb.AppendLine('It ships with the components below, each under its own licence, reproduced here as those licences ask.')
[void]$sb.AppendLine('This file is generated by licenses\update-notices.ps1; don''t edit it by hand.')
[void]$sb.AppendLine()
foreach ($g in $groups.Values) {
    [void]$sb.AppendLine($rule)
    foreach ($p in $g.Packages) { [void]$sb.AppendLine($p) }
    [void]$sb.AppendLine("Licence: $($g.Kind)")
    [void]$sb.AppendLine($thin)
    [void]$sb.AppendLine($g.Text)
    [void]$sb.AppendLine()
}
[void]$sb.Append((Get-Content (Join-Path $PSScriptRoot 'extra-notices.txt') -Raw).TrimEnd())
[void]$sb.AppendLine()
[void]$sb.AppendLine()
[void]$sb.AppendLine($rule)
[void]$sb.AppendLine('Apache License, Version 2.0 (for the packages marked Apache-2.0 above)')
[void]$sb.AppendLine($thin)
[void]$sb.Append((Get-Content (Join-Path $PSScriptRoot 'Apache-2.0.txt') -Raw).TrimEnd())
[void]$sb.AppendLine()

$text = $sb.ToString() -replace "`r`n", "`n"
[IO.File]::WriteAllText($out, $text, [Text.UTF8Encoding]::new($false))
$count = ($groups.Values | ForEach-Object { $_.Packages.Count } | Measure-Object -Sum).Sum
Write-Host "Third-party notices: $count packages in $($groups.Count) entries -> src\Plicbox.App\THIRD-PARTY-NOTICES.txt"
